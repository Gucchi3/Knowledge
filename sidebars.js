// @ts-check
// 分野ごとに1つのサイドバーを作る。中身は各分野のフォルダから自動で作る。

const {listFields} = require('./fields');

/** @type {import('@docusaurus/plugin-content-docs').SidebarsConfig} */
const sidebars = Object.fromEntries(
  listFields().map((field) => [field.id, [{type: 'autogenerated', dirName: field.id}]]),
);

module.exports = sidebars;
